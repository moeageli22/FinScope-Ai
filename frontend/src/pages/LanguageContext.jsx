const languageNames = {
    en: { name: 'English', flag: '🇬🇧', nativeName: 'English' },
    es: { name: 'Spanish', flag: '🇪🇸', nativeName: 'Español' },
    fr: { name: 'French', flag: '🇫🇷', nativeName: 'Français' },
    ar: { name: 'Arabic', flag: '🇸🇦', nativeName: 'العربية', rtl: true },
    de: { name: 'German', flag: '🇩🇪', nativeName: 'Deutsch' },
};

export const LanguageProvider = ({ children }) => {
    const [language, setLanguage] = useState(() => {
        return localStorage.getItem('finscope_language') || 'en';
    });

    const t = useCallback((key) => {
        return translations[language]?.[key] || translations.en[key] || key;
    }, [language]);

    const changeLanguage = useCallback((lang) => {
        setLanguage(lang);
        localStorage.setItem('finscope_language', lang);
        // Set RTL direction for Arabic
        if (languageNames[lang]?.rtl) {
            document.documentElement.dir = 'rtl';
            document.documentElement.lang = lang;
        } else {
            document.documentElement.dir = 'ltr';
            document.documentElement.lang = lang;
        }
    }, []);

    useEffect(() => {
        // Apply direction on initial load
        if (languageNames[language]?.rtl) {
            document.documentElement.dir = 'rtl';
        } else {
            document.documentElement.dir = 'ltr';
        }
        document.documentElement.lang = language;
    }, [language]);

    return (
        <LanguageContext.Provider value={{ language, changeLanguage, t, languages: languageNames }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
};

export default LanguageContext;